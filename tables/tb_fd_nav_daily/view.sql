CREATE VIEW tytdata.tb_fd_nav_daily (
    c_trade_date COMMENT '交易日期',
    c_fd_code COMMENT '基金代码',
    c_nav COMMENT '单位净值',
    c_nav_acc COMMENT '累计单位净值',
    c_nav_adj COMMENT '复权单位净值',
    c_nav_adj_pre COMMENT '昨复权单位净值',
    c_ret_tw COMMENT '本周净值增长率',
    c_ret_tm COMMENT '本月净值增长率',
    c_ret_adj_estab COMMENT '成立至今复权净值增长率',
    c_ret_estab COMMENT '成立至今净值增长率',
    c_ret_ann COMMENT '年化总回报',
    c_ret_1w COMMENT '最近1周净值增长率',
    c_ret_1m COMMENT '最近1月净值增长率',
    c_ret_3m COMMENT '最近3月净值增长率',
    c_ret_6m COMMENT '最近6月净值增长率',
    c_ret_1y COMMENT '最近1年净值增长率',
    c_ret_2y COMMENT '最近2年净值增长率',
    c_ret_3y COMMENT '最近3年净值增长率',
    c_ret_4y COMMENT '最近4年净值增长率',
    c_ret_5y COMMENT '最近5年净值增长率',
    c_ret_ytd COMMENT '今年以来净值增长率',
    c_ret_ly COMMENT '去年净值增长率',
    c_ret_2ya COMMENT '前年净值增长率',
    c_ret_3ya COMMENT '往前第三年净值增长率',
    c_ret_4ya COMMENT '往前第四年净值增长率',
    c_ret_5ya COMMENT '往前第五年净值增长率',
    c_log_ret_adj COMMENT '当日复权净值对数收益率',
    c_purchase_status COMMENT '申购状态',
    c_redeem_status COMMENT '赎回状态',
    c_ret_1d COMMENT '当日净值增长率',
    c_is_predict COMMENT '是否预测',
    c_ret_1d_raw COMMENT '当日净值增长率(不复权)',
    c_is_trade COMMENT '是否交易日'
) COMMENT '基金每日净值' AS
SELECT
    a.ENDDATE AS c_trade_date,
    a.SECURITYCODE AS c_fd_code,
    a.NVPER AS c_nav,
    a.ANVPER AS c_nav_acc,
    a.AANVPER AS c_nav_adj,
    a.AANVPERL AS c_nav_adj_pre,
    a.NVYIELDTW AS c_ret_tw,
    a.NVYIELDTM AS c_ret_tm,
    a.AANVGRF AS c_ret_adj_estab,
    a.NVGRF AS c_ret_estab,
    a.AAYIELD AS c_ret_ann,
    a.NVGRW1W AS c_ret_1w,
    a.NVGR4W AS c_ret_1m,
    a.NVGR13W AS c_ret_3m,
    a.NVGR26W AS c_ret_6m,
    a.NVGR52W AS c_ret_1y,
    a.NVGR104W AS c_ret_2y,
    a.NVGR156W AS c_ret_3y,
    a.NVGR208W AS c_ret_4y,
    a.NVGR260W AS c_ret_5y,
    a.NVGRTY AS c_ret_ytd,
    a.YIELDLY AS c_ret_ly,
    a.YIELD2YA AS c_ret_2ya,
    a.YIELD3YA AS c_ret_3ya,
    a.YIELD4YA AS c_ret_4ya,
    a.YIELD5YA AS c_ret_5ya,
    a.NVCHG AS c_log_ret_adj,
    a.PURTYPE AS c_purchase_status,
    a.REDTYPE AS c_redeem_status,
    a.NVGRWTD AS c_ret_1d,
    a.IS_PREDICT AS c_is_predict,
    a.NVPERCHG AS c_ret_1d_raw,
    b.IS_D AS c_is_trade
FROM TYTFUND.FUND_DR_FUNDNV a
LEFT JOIN TYTFUND.QT_TRADE_CALENDAR b
    ON a.ENDDATE = b.TRADE_DT
WHERE a.EISDEL = '0'