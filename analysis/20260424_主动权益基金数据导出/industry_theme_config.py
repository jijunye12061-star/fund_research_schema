# ============= 工具函数 =============

def get_theme(ind_code: str) -> str:
    """根据行业代码获取板块主题"""
    return CODE_TO_THEME.get(str(ind_code))


def get_ind_name(ind_code: str) -> str:
    """根据行业代码获取行业名称"""
    return CODE_TO_NAME.get(str(ind_code))


def get_industries_by_level1(level1_name: str) -> list:
    """获取某一级行业的所有三级行业"""
    return INDUSTRY_CONFIG.get(level1_name, [])


def get_codes_by_theme(theme: str) -> list:
    """获取某板块的所有行业代码"""
    return [code for code, t in CODE_TO_THEME.items() if t == theme]


def get_codes_by_level1(level1_name: str) -> list:
    """获取某一级行业的所有代码"""
    return [item["ind_code"] for item in INDUSTRY_CONFIG.get(level1_name, [])]


def get_all_level1() -> list:
    """获取所有一级行业名称"""
    return list(INDUSTRY_CONFIG.keys())


def get_all_themes() -> list:
    """获取所有板块主题"""
    return list(set(CODE_TO_THEME.values()))


